#!/usr/bin/env node
// Recreate the four throwaway build artefacts the design-sync converter needs,
// and re-derive componentSrcMap from the emitted declarations.
//
//   node .design-sync/prepare.mjs
//
// @repo/ui is source-only on purpose (see NOTES.md): exports point straight at
// .tsx, there is no dist/ and no build script. The converter needs a built
// entry plus a .d.ts tree, so this synthesises a throwaway one. Everything it
// writes is gitignored and safe to delete:
//
//   packages/ui/src/_ds-entry.ts          barrel over every source file
//   packages/ui/src/_ds-styles.css        Tailwind entry (+ .built.css)
//   packages/ui/.ds-tsconfig.json         emitDeclarationOnly config
//   packages/ui/.ds-dist/                 index.d.ts + index.es.js + styles.css
//   packages/ui/.ds-fonts/                Geist, latin subset, + fonts.css
//
// Then run the converter:
//
//   node .ds-sync/package-build.mjs --config .design-sync/config.json \
//     --node-modules packages/ui/node_modules \
//     --entry packages/ui/.ds-dist/index.es.js --out ./ds-bundle

import { spawnSync } from "node:child_process";
import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const ui = join(root, "packages/ui");
const dist = join(ui, ".ds-dist");
const fontsDir = join(ui, ".ds-fonts");
const configPath = join(root, ".design-sync/config.json");

// Roots whose exported component does not match the filename, and files that
// ship in the bundle but get no card (pure providers, no visual output).
const HAND_PINNED = {
  chart: "ChartContainer",
  "data-table": "DataTableView",
  "input-otp": "InputOTP",
  resizable: "ResizablePanelGroup",
};
const NO_CARD = new Set([
  "components/direction",
  "blocks/theme",
  "blocks/password-input",
]);

const problems = [];
const step = (n) => console.log(`\n== ${n}`);

function run(cmd, args, cwd = ui) {
  const r = spawnSync(cmd, args, { cwd, stdio: "inherit" });
  if (r.status !== 0) {
    throw new Error(`${cmd} ${args.join(" ")} exited ${r.status ?? r.error}`);
  }
}

function sourceFiles() {
  const out = [];
  for (const [dir, ext] of [
    ["components", ".tsx"],
    ["blocks", ".tsx"],
    ["hooks", ".ts"],
    ["lib", ".ts"],
  ]) {
    const files = readdirSync(join(ui, "src", dir))
      .filter((f) => f.endsWith(ext) && !f.includes(".test."))
      .sort();
    for (const f of files) out.push(`${dir}/${f.slice(0, -ext.length)}`);
  }
  return out;
}

const pascal = (slug) =>
  slug.replace(/(^|-)([a-z0-9])/g, (_, __, c) => c.toUpperCase());

// ---------------------------------------------------------------------------

const modules = sourceFiles();

step(`barrel entry — ${modules.length} modules`);
writeFileSync(
  join(ui, "src/_ds-entry.ts"),
  [
    "// generated by .design-sync/prepare.mjs — temporary barrel entry, safe to delete",
    ...modules.map((m) => `export * from "./${m}";`),
    "",
  ].join("\n"),
);

step("Tailwind entry");
// The package ships no CSS — the apps build their own — so the sync compiles
// its own stylesheet. The previews @source is load-bearing: authored previews
// live outside the package, and a utility used only in a preview is otherwise
// never generated and that card renders unstyled.
writeFileSync(
  join(ui, "src/_ds-styles.css"),
  `/* generated by .design-sync/prepare.mjs — temporary Tailwind entry, safe to delete */
@import "tailwindcss";
@import "./styles/globals.css";
@import "./styles/tagaroa.css";
@source "./";
@source "../../../.design-sync/previews";
`,
);

step("declarations (tsc --emitDeclarationOnly)");
// TypeScript 7 removed baseUrl — it errors if present, so paths are absolute.
const tsconfigPath = join(ui, ".ds-tsconfig.json");
writeFileSync(
  tsconfigPath,
  JSON.stringify(
    {
      extends: "./tsconfig.json",
      compilerOptions: {
        noEmit: false,
        declaration: true,
        declarationMap: false,
        emitDeclarationOnly: true,
        // The package's own config is NodeNext, which demands ".js" on every
        // relative import. The barrel is extensionless and esbuild bundles it.
        module: "esnext",
        moduleResolution: "bundler",
        rootDir: join(ui, "src"),
        outDir: dist,
        paths: { "@repo/ui/*": [join(ui, "src/*")] },
      },
      include: [join(ui, "src/**/*")],
      exclude: [join(ui, "src/**/*.test.*")],
    },
    null,
    2,
  ),
);
rmSync(dist, { recursive: true, force: true });
run(join(ui, "node_modules/.bin/tsc"), ["-p", tsconfigPath]);
copyFileSync(join(dist, "_ds-entry.d.ts"), join(dist, "index.d.ts"));

step("componentSrcMap");
// The converter treats every PascalCase .d.ts export as a component, which for
// a compound library is 300+ cards. Pin the roots to their source files and
// null the rest: the subcomponents still ship and stay usable, they just get
// no card of their own.
const exported = new Set();
(function walk(dir) {
  for (const e of readdirSync(dir, { withFileTypes: true })) {
    const p = join(dir, e.name);
    if (e.isDirectory()) {
      walk(p);
      continue;
    }
    if (
      !e.name.endsWith(".d.ts") ||
      /^(index|_ds-entry)\.d\.ts$/.test(e.name)
    ) {
      continue;
    }
    const src = readFileSync(p, "utf8");
    for (const m of src.matchAll(/export\s+(type\s+)?\{([\s\S]*?)\}/g)) {
      if (m[1]) continue; // export type { … }
      for (let name of m[2].split(",")) {
        name = name.trim();
        if (!name || /^type\s/.test(name)) continue;
        name = name
          .split(/\s+as\s+/)
          .pop()
          .trim();
        if (/^[A-Z]/.test(name)) exported.add(name);
      }
    }
    for (const m of src.matchAll(
      /^export\s+declare\s+(?:abstract\s+)?(?:function|const|class)\s+([A-Za-z0-9_$]+)/gm,
    )) {
      if (/^[A-Z]/.test(m[1])) exported.add(m[1]);
    }
  }
})(dist);

const roots = new Map();
for (const m of modules) {
  if (NO_CARD.has(m) || m.startsWith("hooks/") || m.startsWith("lib/"))
    continue;
  const slug = m.slice(m.indexOf("/") + 1);
  const name = HAND_PINNED[slug] ?? pascal(slug);
  if (!exported.has(name)) {
    problems.push(
      `${m}.tsx exports no "${name}" — add it to HAND_PINNED or NO_CARD in prepare.mjs`,
    );
    continue;
  }
  roots.set(name, `../src/${m}.tsx`);
}

const config = JSON.parse(readFileSync(configPath, "utf8"));
const before = Object.keys(config.componentSrcMap ?? {});
config.componentSrcMap = Object.fromEntries(
  [...exported].sort().map((name) => [name, roots.get(name) ?? null]),
);
writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`);
const added = [...exported].filter((n) => !before.includes(n));
const dropped = before.filter((n) => !exported.has(n));
console.log(
  `${roots.size} roots, ${exported.size - roots.size} nulled` +
    (added.length ? ` · added ${added.join(", ")}` : "") +
    (dropped.length ? ` · dropped ${dropped.join(", ")}` : ""),
);

step("JS entry (esbuild)");
// --packages=external matters: the converter re-bundles and resolves
// dependencies itself via --node-modules.
run("bunx", [
  "esbuild@0.25.12",
  "src/_ds-entry.ts",
  "--bundle",
  "--format=esm",
  "--packages=external",
  "--jsx=automatic",
  `--outfile=${join(dist, "index.es.js")}`,
]);

// The converter reads `types` from this and fails with a bare ENOENT without it.
writeFileSync(
  join(dist, "package.json"),
  `${JSON.stringify(
    {
      name: "@repo/ui",
      type: "module",
      module: "index.es.js",
      types: "index.d.ts",
    },
    null,
    2,
  )}\n`,
);

step("fonts");
// tagaroa.css names the Geist families; fontsource ships them. Resolve from
// whichever app has them installed rather than pinning one.
mkdirSync(fontsDir, { recursive: true });
const faces = [
  ["Geist Variable", "geist", "normal"],
  ["Geist Variable", "geist", "italic"],
  ["Geist Mono Variable", "geist-mono", "normal"],
  ["Geist Mono Variable", "geist-mono", "italic"],
];
const apps = [
  "apps/admin",
  "apps/auth",
  "apps/workspace",
  "domains/engineering",
];
const faceCss = [];
for (const [family, pkg, style] of faces) {
  const file = `${pkg}-latin-wght-${style}.woff2`;
  const from = apps
    .map((a) =>
      join(root, a, "node_modules/@fontsource-variable", pkg, "files", file),
    )
    .find(existsSync);
  if (!from) {
    problems.push(
      `${file} not found — run \`bun install\`; cards will render in a fallback face`,
    );
    continue;
  }
  copyFileSync(from, join(fontsDir, file));
  faceCss.push(`@font-face {
  font-family: "${family}";
  font-style: ${style};
  font-display: swap;
  font-weight: 100 900;
  src: url("./${file}") format("woff2-variations");
}`);
}
writeFileSync(
  join(fontsDir, "fonts.css"),
  `/* generated by .design-sync/prepare.mjs — Geist, latin subset */\n${faceCss.join("\n")}\n`,
);
console.log(`${faceCss.length} @font-face rule(s)`);

step("CSS (Tailwind v4)");
// Compiled after the previews are on disk: @source only picks up classes that
// exist at compile time.
const twManifest = apps
  .map((a) => join(root, a, "node_modules/tailwindcss/package.json"))
  .find(existsSync);
if (!twManifest)
  throw new Error("tailwindcss not installed — run `bun install`");
const twVersion = JSON.parse(readFileSync(twManifest, "utf8")).version;
run("bunx", [
  `@tailwindcss/cli@${twVersion}`,
  "-i",
  "src/_ds-styles.css",
  "-o",
  "src/_ds-styles.built.css",
]);
copyFileSync(join(ui, "src/_ds-styles.built.css"), join(dist, "styles.css"));

step("checks");
for (const [dir, ext] of [
  [".design-sync/docs", ".md"],
  [".design-sync/previews", ".tsx"],
]) {
  const have = new Set(
    readdirSync(join(root, dir)).map((f) => f.slice(0, -ext.length)),
  );
  for (const name of roots.keys()) {
    if (!have.has(name)) problems.push(`${dir}/${name}${ext} is missing`);
  }
  for (const name of have) {
    if (!roots.has(name))
      problems.push(`${dir}/${name}${ext} has no root component`);
  }
}
for (const f of ["index.d.ts", "index.es.js", "styles.css", "package.json"]) {
  if (!existsSync(join(dist, f)))
    problems.push(`.ds-dist/${f} was not written`);
}

if (problems.length) {
  console.error(`\n${problems.length} problem(s):`);
  for (const p of problems) console.error(`  ! ${p}`);
  process.exit(1);
}
console.log(`ok — ${relative(root, dist)} is ready for package-build.mjs`);
